import numpy as np
import pandas as pd

from sentence_transformers import SentenceTransformer
import src.config as config

DATA_PATH = "data/amazonhelp_cleaned_with_intents.csv"
MODEL_NAME = config.EMBEDDING_MODEL

RANDOM_STATE = config.RANDOM_STATE
TEST_SIZE = config.TEST_SIZE


def load_data():

    data = pd.read_csv(DATA_PATH)

    labeled_data = data[
        data["Intent"].notna()
    ].copy()

    historical_data = data[
        data["Intent"].isna()
    ].copy()

    return labeled_data, historical_data


def evaluate_retrieval(
    labeled_data,
    historical_data,
    model,
    top_k_values=(1, 3, 5, 10)
):

    from sklearn.model_selection import train_test_split

    _, test_data = train_test_split(
        labeled_data,
        test_size=TEST_SIZE,
        random_state=RANDOM_STATE,
        stratify=labeled_data["Intent"]
    )

    print("Generating historical embeddings...")

    historical_embeddings = model.encode(
        historical_data[
            "cleaned_customer_message"
        ].tolist(),
        convert_to_numpy=True,
        normalize_embeddings=True,
        show_progress_bar=True
    )

    print("Generating test embeddings...")

    test_embeddings = model.encode(
        test_data[
            "cleaned_customer_message"
        ].tolist(),
        convert_to_numpy=True,
        normalize_embeddings=True,
        show_progress_bar=True
    )

    results = {}

    for k in top_k_values:

        hits = 0

        for query_embedding, true_intent in zip(
            test_embeddings,
            test_data["Intent"]
        ):

            scores = historical_embeddings @ query_embedding

            top_idx = np.argsort(scores)[-k:][::-1]

            retrieved_intents = historical_data.iloc[
                top_idx
            ]["Intent"].values

            # Historical cases do not have human labels.
            # Therefore their intent consistency is estimated
            # using the trained classifier outside this metric.
            #
            # This function is intentionally kept as the
            # retrieval implementation; evaluation should use
            # pseudo-intents generated by the classifier.

        results[k] = hits / len(test_data)

    return results


